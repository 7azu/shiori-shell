#!/bin/bash
# hyprtoolkit apps (hyprland-share-picker = screen picker when streaming in Vesktop/Zen/OBS,
# no longer Qt since xdg-desktop-portal-hyprland 1.5.0) in the pywal colors.
# Writes ~/.cache/wal/hyprtoolkit.conf, ~/.config/hypr/hyprtoolkit.conf is a link to it
# (this way only the link is in the repo, not the colors of each wallpaper).
# Color mapping as in gen-qt6ct-colors.sh, so the picker looks like the Qt dialogs.
# Runs on every wallpaper change (wallpaper-apps.sh); the picker reads the file again on every start.
set -u

COLORS="$HOME/.cache/wal/colors.json"
[ -f "$COLORS" ] || exit 0

python3 -I - "$COLORS" "$HOME/.cache/wal/hyprtoolkit.conf" <<'PY'
import json, sys
from pathlib import Path

c = json.load(open(sys.argv[1]))
bg, fg = c["special"]["background"], c["special"]["foreground"]
accent, accent2 = c["colors"]["color4"], c["colors"]["color5"]

def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
def hexc(t): return "#" + "".join(f"{round(max(0, min(255, x))):02x}" for x in t)
def mix(a, b, t): return hexc(x + (y - x) * t for x, y in zip(rgb(a), rgb(b)))
def lum(h):
    ch = [x / 255 for x in rgb(h)]
    ch = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in ch]
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]
def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)
def col(h): return f"rgba({h[1:].lower()}ff)"

on_accent = bg if contrast(accent, bg) >= contrast(accent, fg) else fg
values = {
    "background": bg,                         # Qt: Window
    "base": mix(bg, fg, 0.10),                # Qt: Button (tiles/buttons in the picker)
    "alternate_base": mix(bg, fg, 0.18),      # Qt: Mid (Hover)
    "text": fg,
    "bright_text": on_accent,                 # text on the accent color (Qt: HighlightedText)
    "accent": accent,                         # Qt: Highlight
    "accent_secondary": accent2,
}
out = "# Generated by ~/.config/wal/hyprtoolkit/gen-hyprtoolkit-colors.sh - do not edit by hand\n"
out += "".join(f"{k} = {col(v)}\n" for k, v in values.items())
out += "font_family = Adwaita Sans\nicon_theme = breeze-dark\n"   # like qt6ct/GTK
p = Path(sys.argv[2])
if not p.exists() or p.read_text() != out:
    p.write_text(out)
PY

link="$HOME/.config/hypr/hyprtoolkit.conf"
[ -L "$link" ] || [ ! -e "$link" ] && ln -sfn ../../.cache/wal/hyprtoolkit.conf "$link"
exit 0
