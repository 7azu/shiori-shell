#!/bin/bash
# Fcitx5 theme "wal" from the current pywal colors (candidate window + tray menu).
# Fcitx5 uses no GTK theme but its own themes in ~/.local/share/fcitx5/themes.
# Runs on every wallpaper change (wallpaper-apps.sh); sets the theme up itself on the first run
# (classicui.conf: Theme=wal) and reloads it in a running Fcitx5.
set -u

THEME="$HOME/.local/share/fcitx5/themes/wal"
CONF="$HOME/.config/fcitx5/conf/classicui.conf"
COLORS="$HOME/.cache/wal/colors.json"
[ -f "$COLORS" ] || exit 0

mkdir -p "$THEME"
# Arrows/radio from default-dark, tinted in the text color (below)
for f in arrow next prev radio; do
    [ -f "/usr/share/fcitx5/themes/default-dark/$f.svg" ] && cp "/usr/share/fcitx5/themes/default-dark/$f.svg" "$THEME/$f.svg"
done

python3 -I - "$COLORS" "$THEME" <<'EOF'
import json, sys
from pathlib import Path
c = json.load(open(sys.argv[1]))
theme = Path(sys.argv[2])
bg, fg = c["special"]["background"], c["special"]["foreground"]
accent = c["colors"]["color4"]  # accent like in Quickshell/Steam

def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
def hexc(t): return "#" + "".join(f"{round(x):02x}" for x in t)
def mix(a, b, t): return hexc(x + (y - x) * t for x, y in zip(rgb(a), rgb(b)))
def lum(h):
    ch = [x / 255 for x in rgb(h)]
    ch = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in ch]
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]
def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)

# Text on the accent: background or foreground, whichever is more readable
on_accent = bg if contrast(accent, bg) >= contrast(accent, fg) else fg
border = mix(bg, fg, 0.15)
dim = mix(bg, fg, 0.6)
sep = mix(bg, fg, 0.25)

for f in theme.glob("*.svg"):
    f.write_text(f.read_text().replace("#c0c0c0", dim))

(theme / "theme.conf").write_text(f"""# Generated by ~/.config/wal/fcitx5/gen-fcitx5-theme.sh - do not edit by hand
[Metadata]
Name=wal
Version=1
Author=pywal
Description=Fcitx5 in den aktuellen pywal-Farben
ScaleWithDPI=True

[InputPanel]
NormalColor={fg}
HighlightCandidateColor={on_accent}
HighlightColor={on_accent}
HighlightBackgroundColor={accent}
PageButtonAlignment=Last Candidate

[InputPanel/TextMargin]
Left=6
Right=6
Top=5
Bottom=5

[InputPanel/ContentMargin]
Left=3
Right=3
Top=3
Bottom=3

[InputPanel/Background]
Color={bg}
BorderColor={border}
BorderWidth=2

[InputPanel/Background/Margin]
Left=2
Right=2
Top=2
Bottom=2

[InputPanel/Highlight]
Color={accent}

[InputPanel/Highlight/Margin]
Left=5
Right=5
Top=5
Bottom=5

[InputPanel/PrevPage]
Image=prev.svg

[InputPanel/PrevPage/ClickMargin]
Left=5
Right=5
Top=4
Bottom=4

[InputPanel/NextPage]
Image=next.svg

[InputPanel/NextPage/ClickMargin]
Left=5
Right=5
Top=4
Bottom=4

[Menu]
NormalColor={fg}
HighlightCandidateColor={on_accent}

[Menu/Background]
Color={bg}
BorderColor={border}
BorderWidth=2

[Menu/Background/Margin]
Left=2
Right=2
Top=2
Bottom=2

[Menu/ContentMargin]
Left=2
Right=2
Top=2
Bottom=2

[Menu/CheckBox]
Image=radio.svg

[Menu/SubMenu]
Image=arrow.svg

[Menu/Highlight]
Color={accent}

[Menu/Highlight/Margin]
Left=5
Right=5
Top=5
Bottom=5

[Menu/Separator]
Color={sep}

[Menu/TextMargin]
Left=5
Right=5
Top=5
Bottom=5
""")
EOF

# Activate the theme (light and dark), system accent off, otherwise it overrides our colors
mkdir -p "$(dirname "$CONF")"
touch "$CONF"
for kv in "Theme=wal" "DarkTheme=wal" "UseAccentColor=False"; do
    key=${kv%%=*}
    if grep -q "^$key=" "$CONF"; then
        sed -i "s|^$key=.*|$kv|" "$CONF"
    else
        echo "$kv" >>"$CONF"
    fi
done

# A running Fcitx5 reloads the theme right away
command -v busctl >/dev/null && busctl --user call org.fcitx.Fcitx5 /controller \
    org.fcitx.Fcitx.Controller1 ReloadAddonConfig s classicui >/dev/null 2>&1
exit 0
