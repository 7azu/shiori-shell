#!/bin/bash
# OBS Studio in the pywal colors: variant "Wal" of the default theme Yami
# (~/.config/obs-studio/themes/Wal.ovt). Only color variables are overridden, the layout
# stays Yami -> survives OBS updates. Select it once: Settings > Appearance >
# theme "Yami", style "Wal".
# Live recoloring: OBS only watches theme files with the hidden option
# [Appearance] AutoReload=true in user.ini. This script sets it (and selects the theme "Wal" if no
# theme was chosen yet), but only when OBS is not running - OBS writes user.ini back from memory on
# exit and would otherwise discard it again. So it applies from the next OBS start.
# Color mapping as in the GTK theme Wal (wal/templates/gtk3-colors.css).
# Runs twice on every wallpaper change: already at the start of the wave from Quickshell with the new
# palette as an argument (JSON list with 16 colors; crossfade with a still image:
# quickshell/services/TerminalColorFade.qml, obsFade), then from wallpaper-apps.sh without an argument
# (reads colors.json, same content -> the file stays untouched, OBS does not reload again).
set -u

COLORS="$HOME/.cache/wal/colors.json"
[ -f "$COLORS" ] || exit 0
mkdir -p "$HOME/.config/obs-studio/themes"

ini="$HOME/.config/obs-studio/user.ini"
if [ -f "$ini" ] && ! pgrep -x obs >/dev/null; then
    python3 -I - "$ini" <<'EOF'
import re, sys
p = sys.argv[1]
s = open(p).read()
sec = re.search(r"^\[Appearance\][^\n]*\n(.*?)(?=^\[|\Z)", s, re.S | re.M)
if sec is None:
    s = s.rstrip("\n") + "\n\n[Appearance]\nAutoReload=true\nTheme=com.obsproject.Yami.Wal\n"
else:
    body = sec.group(1)
    if re.search(r"^AutoReload=", body, re.M):
        body = re.sub(r"^AutoReload=.*$", "AutoReload=true", body, flags=re.M)
    else:
        body = "AutoReload=true\n" + body
    # Theme only when none was chosen yet (a theme picked by hand stays)
    if not re.search(r"^Theme=", body, re.M):
        body = "Theme=com.obsproject.Yami.Wal\n" + body
    s = s[:sec.start(1)] + body + s[sec.end(1):]
if s != open(p).read():
    open(p, "w").write(s)
EOF
fi

python3 -I - "$COLORS" "$HOME/.config/obs-studio/themes/Wal.ovt" "${1:-}" <<'EOF'
import json, re, sys

out = sys.argv[2]
if len(sys.argv) > 3 and sys.argv[3]:
    # Palette from Quickshell (16 colors as a JSON list), already at the start of the wallpaper wave;
    # as with wal: background = color0, foreground = color15
    pal = json.loads(sys.argv[3])
    if not (isinstance(pal, list) and len(pal) == 16
            and all(isinstance(x, str) and re.fullmatch(r"#[0-9a-fA-F]{6}", x) for x in pal)):
        sys.exit(1)
    bg, fg, accent = pal[0], pal[15], pal[4]
else:
    c = json.load(open(sys.argv[1]))
    bg, fg = c["special"]["background"], c["special"]["foreground"]
    accent = c["colors"]["color4"]
# lower case, so both paths (Quickshell / colors.json) give the same file and OBS does not load twice
bg, fg, accent = bg.lower(), fg.lower(), accent.lower()

def rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
def hexc(t): return "#" + "".join(f"{round(max(0, min(255, x))):02x}" for x in t)
def mix(a, b, t): return hexc(x + (y - x) * t for x, y in zip(rgb(a), rgb(b)))
def lum(h):
    ch = [x / 255 for x in rgb(h)]
    ch = [x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4 for x in ch]
    return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]
def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)

# Yami always writes --text on --primary (selection, tabs, buttons). So darken bright wal accents
# toward black (keeps the hue) until the text on them is readable.
t = 0.0
while t < 0.9 and contrast(mix(accent, "#000000", t), fg) < 4.5:
    t += 0.05
primary = mix(accent, "#000000", t)

# Gray tones grey1 (light) .. grey8 (dark) between background and foreground; grey7 = window
black = "#000000"
greys = [mix(bg, fg, 0.30), mix(bg, fg, 0.24), mix(bg, fg, 0.18), mix(bg, fg, 0.12),
         mix(bg, fg, 0.07), mix(bg, fg, 0.03), bg, mix(bg, black, 0.25)]

v = {f"grey{i + 1}": g for i, g in enumerate(greys)}
v.update({
    "primary": primary,
    "primary_light": mix(primary, accent, 0.35),
    "primary_lighter": mix(primary, accent, 0.7),
    "primary_dark": mix(primary, bg, 0.3),
    "primary_darker": mix(primary, bg, 0.55),
    "text": fg,
    "text_light": fg,
    "text_muted": mix(bg, fg, 0.6),
    "text_inactive": fg,
    "separator_hover": fg,
    "palette_link": accent,
    "palette_linkVisited": accent,
    "bg_preview": mix(bg, black, 0.35),
})

lines = "\n".join(f"    --{k}: {val};" for k, val in v.items())
theme = f"""/* Generated by ~/.config/wal/obs/gen-obs-theme.sh - do not edit by hand */

@OBSThemeMeta {{
    name: 'Wal';
    id: 'com.obsproject.Yami.Wal';
    extends: 'com.obsproject.Yami';
    author: 'pywal';
    dark: '{"true" if lum(bg) < 0.5 else "false"}';
}}

@OBSThemeVars {{
{lines}
}}
"""
# Write in place (no rename), so OBS' file watcher keeps watching the file
try:
    if open(out).read() == theme:
        sys.exit(0)
except FileNotFoundError:
    pass
with open(out, "w") as f:
    f.write(theme)
EOF
