#!/bin/bash
# Creates the default cover for rmpc (shown when a song has no cover) in the
# current wal colors: a record, the label in the strongest wal color.
# Called after every wallpaper change (~/.config/hypr/scripts/wallpaper-apps.sh)
#
# Live update: rmpc reads its fallback cover (theme: default_album_art_path) only at start.
# That is why the image also lies as cover.png in the music folder: MPD serves it for songs without
# an embedded cover (rmpc asks for the embedded one first), and rmpc fetches it fresh on every
# song change or theme change. The theme stays as the fallback for the start.

COVER="$HOME/.cache/wal/rmpc-default-cover.png"
THEME="$HOME/.config/rmpc/themes/wal.ron"
# Music folder from the shiori-shell settings ("music", must match music_directory in mpd.conf)
MUSIC_DIR=$(python3 "$HOME/.config/quickshell/scripts/shiori_settings.py" folder music 2>/dev/null)
MUSIC_COVER="${MUSIC_DIR:-$HOME/Music}/cover.png"

read -r BG DISC GROOVE ACCENT < <(python3 - << 'PYEOF'
import json, os

wal = json.load(open(os.path.expanduser("~/.cache/wal/colors.json")))
c, s = wal["colors"], wal["special"]

def h2t(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

def hexs(t):
    return "#" + "".join(f"{round(x):02x}" for x in t)

def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))

bg, fg = h2t(s["background"]), h2t(s["foreground"])
# Strongest color slot 1-6 as in the Obsidian snippet
accent = max((h2t(c[f"color{i}"]) for i in range(1, 7)), key=lambda t: max(t) - min(t))

print(hexs(mix(bg, fg, 0.07)),      # background of the tile
      hexs(mix(bg, (0, 0, 0), 0.45)),  # record
      hexs(mix(bg, fg, 0.16)),      # Rillen
      hexs(accent))                 # Label
PYEOF
)

mkdir -p "$(dirname "$COVER")" "$(dirname "$THEME")"
magick -size 500x500 xc:none \
    -fill "$BG" -draw "roundrectangle 0,0 499,499 44,44" \
    -fill "$DISC" -draw "circle 250,250 250,58" \
    -fill none -stroke "$GROOVE" -strokewidth 2 \
    -draw "circle 250,250 250,84" -draw "circle 250,250 250,108" -draw "circle 250,250 250,132" \
    -stroke none -fill "$ACCENT" -draw "circle 250,250 250,178" \
    -fill "$BG" -draw "circle 250,250 250,240" \
    -depth 8 "$COVER" || exit 1

# Only write the theme if it really changes: rmpc watches its config and reloads everything on every
# change - including the re-sent cover, which briefly disappears meanwhile. The content is always
# the same (fixed image path); before, the wal ID was in the comment, so the file changed
# on every wallpaper change and triggered a needless reload.
NEW_THEME=$(cat << EOF
#![enable(implicit_some)]
#![enable(unwrap_newtypes)]
#![enable(unwrap_variant_newtypes)]
// Auto-generated by ~/.config/wal/gen-rmpc-cover.sh - do not edit by hand.
// Everything else stays at the rmpc default; only the fallback cover comes from the wal colors.
(
    default_album_art_path: "$COVER",
)
EOF
)
[ "$(cat "$THEME" 2>/dev/null)" = "$NEW_THEME" ] || printf '%s\n' "$NEW_THEME" > "$THEME"

# Live: store as the folder cover for MPD
cp -f "$COVER" "$MUSIC_COVER"

# Only let running rmpc instances reload if they show the fallback cover right now, i.e. the
# current song has no own (embedded) cover. Otherwise there is nothing to recolor, and the
# reload only made the real cover disappear briefly (visible on every wallpaper change).
current=$(mpc -f '%file%' current 2>/dev/null)
if [ -n "$current" ] && python3 -I - "$current" << 'PYEOF'
import socket, sys
# MPD: readpicture returns "size: ..." if the file has an embedded image, otherwise only "OK"
uri = sys.argv[1].replace("\\", "\\\\").replace('"', '\\"')
try:
    with socket.create_connection(("127.0.0.1", 6600), timeout=2) as s:
        f = s.makefile("rwb")
        f.readline()
        f.write(f'readpicture "{uri}" 0\n'.encode())
        f.flush()
        sys.exit(0 if f.readline().startswith(b"size:") else 1)
except OSError:
    sys.exit(1)
PYEOF
then
    exit 0
fi

# A song without its own cover is loaded: a theme reload makes the cover view fetch the image fresh from
# MPD (cover.png above). No song loaded: rmpc shows the fallback from the theme, which it reads only at
# start (neither "set theme" nor a changed theme file helps, tested with rmpc 0.11) -> the stage rmpc
# (hypr/scripts/rmpc-stage.sh) is restarted in its window; other instances keep the old fallback.
# Address every running instance separately: "rmpc remote" without --pid aborts at the first orphaned
# socket (/tmp/rmpc-<pid>.sock of an ended instance) with "Connection refused"
for sock in /tmp/rmpc-*.sock; do
    [ -S "$sock" ] || continue
    pid=${sock#/tmp/rmpc-}
    pid=${pid%.sock}
    if ! kill -0 "$pid" 2>/dev/null; then
        rm -f "$sock"
    elif [ -z "$current" ] && grep -qs rmpc-stage.sh "/proc/$(ps -o ppid= -p "$pid" | tr -d ' ')/cmdline"; then
        touch "${XDG_RUNTIME_DIR:-/tmp}/rmpc-stage-restart"
        rmpc remote --pid "$pid" keybind q >/dev/null 2>&1
    else
        rmpc remote --pid "$pid" set theme "$THEME" >/dev/null 2>&1
    fi
done
exit 0
