#!/bin/bash
# Own GTK theme "Wal": widget shapes from adw-gtk3 (GTK3 port of libadwaita), colors from pywal.
# This way GTK3, GTK4 and libadwaita apps look the same. Replaces wpgtk/FlatColor.
#
#   install-gtk-theme.sh            set up (idempotent, runs on every wallpaper change
#                                   from apply-wallpaper.sh -> sets up new machines by itself)
#   install-gtk-theme.sh --reload   also recolor running GTK3 apps
#
# Colors: pywal templates ~/.config/wal/templates/gtk{3,4}-colors.css -> ~/.cache/wal/
# libadwaita ignores themes and only reads ~/.config/gtk-4.0/gtk.css (at app start).
set -u

THEMES="$HOME/.local/share/themes"
WAL="$THEMES/Wal"
ADW_VERSION=v6.5
ICONS=breeze-dark
CACHE="$HOME/.cache/wal"

# adw-gtk3 as the base: system package (adw-gtk-theme) or downloaded here
adw=""
for d in /usr/share/themes/adw-gtk3-dark "$THEMES/adw-gtk3-dark"; do
    [ -f "$d/gtk-3.0/gtk.css" ] && { adw=$d; break; }
done
if [ -z "$adw" ]; then
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' EXIT
    url="https://github.com/lassekongo83/adw-gtk3/releases/download/$ADW_VERSION/adw-gtk3$ADW_VERSION.tar.xz"
    if curl -sfL -o "$tmp/adw.tar.xz" "$url" && tar -xf "$tmp/adw.tar.xz" -C "$tmp"; then
        mkdir -p "$THEMES"
        cp -r "$tmp/adw-gtk3" "$tmp/adw-gtk3-dark" "$THEMES/"
        adw="$THEMES/adw-gtk3-dark"
    else
        echo "adw-gtk3 could not be downloaded" >&2
        exit 1
    fi
fi

# Theme folder: import the base, then the wal colors (later definitions win)
mkdir -p "$WAL/gtk-3.0" "$WAL/gtk-4.0"
cat >"$WAL/index.theme" <<EOF
[Desktop Entry]
Type=X-GNOME-Metatheme
Name=Wal
Comment=adw-gtk3 in pywal-Farben (~/.config/wal/gtk/install-gtk-theme.sh)

[X-GNOME-Metatheme]
GtkTheme=Wal
IconTheme=$ICONS
EOF
for v in 3 4; do
    printf '/* Generated by ~/.config/wal/gtk/install-gtk-theme.sh - do not edit by hand */\n@import url("file://%s/gtk-%s.0/gtk.css");\n@import url("file://%s/gtk%s-colors.css");\n' \
        "$adw" "$v" "$CACHE" "$v" >"$WAL/gtk-$v.0/gtk.css"
done
# GTK4 sometimes looks for gtk-dark.css (prefer-dark), GTK3 for the assets relative to the theme
cp "$WAL/gtk-4.0/gtk.css" "$WAL/gtk-4.0/gtk-dark.css"
cp "$WAL/gtk-3.0/gtk.css" "$WAL/gtk-3.0/gtk-dark.css"
for v in 3 4; do
    [ -d "$adw/gtk-$v.0/assets" ] && ln -sfn "$adw/gtk-$v.0/assets" "$WAL/gtk-$v.0/assets"
done

# libadwaita apps: only the colors (libadwaita brings the shapes itself)
mkdir -p "$HOME/.config/gtk-4.0" "$HOME/.config/gtk-3.0"
# old theme symlinks (e.g. from nwg-look/catppuccin) would divert the writing into nothing
rm -f "$HOME/.config/gtk-4.0/gtk.css" "$HOME/.config/gtk-4.0/gtk-dark.css" "$HOME/.config/gtk-4.0/assets"
printf '/* Generated by ~/.config/wal/gtk/install-gtk-theme.sh - wal colors for libadwaita apps */\n@import url("file://%s/gtk4-colors.css");\n' \
    "$CACHE" >"$HOME/.config/gtk-4.0/gtk.css"

for v in 3 4; do
    cat >"$HOME/.config/gtk-$v.0/settings.ini" <<EOF
[Settings]
gtk-theme-name=Wal
gtk-icon-theme-name=$ICONS
gtk-application-prefer-dark-theme=1
EOF
done

# gsettings are read by GTK4/libadwaita and the settings portal (Wayland)
if command -v gsettings >/dev/null; then
    gsettings set org.gnome.desktop.interface color-scheme prefer-dark
    gsettings set org.gnome.desktop.interface icon-theme "$ICONS"
    if [ "${1:-}" = "--reload" ]; then
        # Switch the theme briefly: GTK3 apps then reload it, including the new colors
        gsettings set org.gnome.desktop.interface gtk-theme Adwaita
        sleep 0.3
    fi
    gsettings set org.gnome.desktop.interface gtk-theme Wal
fi
exit 0
